import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const routes = readFileSync(new URL('../src/tv/routes.ts', import.meta.url), 'utf8')
const remote = readFileSync(new URL('../src/tv/remote.ts', import.meta.url), 'utf8')
const tokens = readFileSync(new URL('../src/tv/tokens.css', import.meta.url), 'utf8')
const foundation = readFileSync(new URL('../src/tv/ui/TvFoundation.tsx', import.meta.url), 'utf8')
const foundationCss = readFileSync(new URL('../src/tv/ui/foundation.css', import.meta.url), 'utf8')
const focusMemory = readFileSync(new URL('../src/tv/ui/focusMemory.ts', import.meta.url), 'utf8')
for (const token of ['--tv-bg:', '--tv-border-focus:', '--tv-safe-x:', '--tv-safe-y:', '--tv-hero-title:', '--tv-focus-ring:']) assert.ok(tokens.includes(token), `missing TV design token ${token}`)
assert.ok(tokens.includes('@media (prefers-reduced-motion: reduce)'), 'TV tokens must respect reduced motion')
for (const component of ['TvShell', 'TvSidebar', 'TvPage', 'TvPageHeader', 'TvFocusButton', 'TvImage', 'TvMediaCard', 'TvRail', 'TvHero', 'TvDialog', 'TvLoadingState', 'TvEmptyState', 'TvErrorState', 'TvOfflineState']) assert.ok(foundation.includes(`function ${component}`) || foundation.includes(`const ${component}`), `missing TV Foundation component ${component}`)
for (const state of ['default', 'selected', 'loading']) assert.ok(foundation.includes(`'${state}'`), `missing TV component state ${state}`)
assert.ok(foundation.includes("loading={eager ? 'eager' : 'lazy'}"), 'TV images must lazy load when not priority')
assert.ok(foundation.includes('items.slice(0, Math.max(1, maxMounted))'), 'TV rails must bound mounted cards')
assert.ok(foundation.includes("event.keyCode === 10009") && foundation.includes("event.keyCode === 461"), 'TV dialogs must close from platform Back keys')
assert.ok(foundation.includes('originRef.current?.focus'), 'TV dialogs must restore originating focus')
assert.ok(focusMemory.includes('railIndex') && focusMemory.includes('verticalOffset') && focusMemory.includes('restoreTvFocus'), 'TV focus memory must retain rail and page position')
for (const viewportRule of ['max-width: 1400px', 'min-width: 3000px']) assert.ok(foundationCss.includes(viewportRule), `missing responsive TV rule ${viewportRule}`)
assert.ok(!foundationCss.includes('transition: all'), 'TV Foundation must avoid unbounded transitions')
for (const path of ['/', '/explore', '/search', '/player', '/library', '/music', '/tv', '/radio', '/podcasts', '/audiobooks', '/motivationals', '/lectures', '/about', '/activate']) assert.ok(routes.includes(`'${path}'`), `missing ${path}`)
assert.ok(routes.includes("kind: 'artist'"), 'missing artist detail route')
assert.ok(routes.includes("kind: 'album'"), 'missing album detail route')
for (const code of ['10009', '461', '415', '413', '417', '412']) assert.ok(remote.includes(code), `missing remote code ${code}`)
assert.ok(remote.includes('document.fullscreenElement'))
assert.ok(remote.includes('hasClosableLayer()'))
assert.ok(remote.includes("key: 'Escape'"))
assert.ok(routes.includes('decodeId'), 'route IDs must fail closed')
const capabilities = readFileSync(new URL('../src/tv/capabilities.ts', import.meta.url), 'utf8')
assert.ok(capabilities.includes("get('lowMemory') === '1'"), 'missing low-memory recovery override')
assert.ok(remote.includes('scrollIntoView'))
assert.ok(remote.includes('parent.scrollTop'))
assert.ok(remote.includes('scrollCurrentRegion'))
assert.ok(remote.includes('queue-item'))
console.log('Universal TV static contract: PASS')
